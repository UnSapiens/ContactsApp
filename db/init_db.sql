/* ==========================================================================
   Скрипт инициализации БД "Справочник людей и контактов" (Firebird 3.0+)
   Кодировка подключения: UTF8
   ========================================================================== */

/* 1. Пользовательские исключения */
CREATE EXCEPTION EX_DUPLICATE_DATA 'Запись с такими данными уже существует!';
CREATE EXCEPTION EX_VALIDATION_ERR 'Ошибка валидации входных данных!';

/* 2. Таблица людей */
CREATE TABLE PERSONS (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LAST_NAME   VARCHAR(100) NOT NULL,
    FIRST_NAME  VARCHAR(100) NOT NULL,
    MIDDLE_NAME VARCHAR(100),
    GENDER      CHAR(1) NOT NULL,
    BIRTH_DATE  DATE NOT NULL,

    CONSTRAINT CHK_PERSONS_GENDER CHECK (GENDER IN ('M', 'F')),
    CONSTRAINT CHK_PERSONS_NAMES  CHECK (TRIM(LAST_NAME) <> '' AND TRIM(FIRST_NAME) <> ''),
    CONSTRAINT CHK_PERSONS_BDATE  CHECK (BIRTH_DATE <= CURRENT_DATE)
);

/* Уникальный индекс по нормализованному ФИО, полу и дате рождения */
CREATE UNIQUE INDEX UQ_PERSONS_IDENTITY ON PERSONS COMPUTED BY (
    UPPER(TRIM(LAST_NAME)) || '|' ||
    UPPER(TRIM(FIRST_NAME)) || '|' ||
    UPPER(TRIM(COALESCE(MIDDLE_NAME, ''))) || '|' ||
    GENDER || '|' ||
    CAST(BIRTH_DATE AS VARCHAR(10))
);

/* 3. Справочник типов контактов */
CREATE TABLE CONTACT_TYPES (
    ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(20) NOT NULL,
    NAME VARCHAR(50) NOT NULL,

    CONSTRAINT UQ_CONTACT_TYPES_CODE UNIQUE (CODE),
    CONSTRAINT UQ_CONTACT_TYPES_NAME UNIQUE (NAME)
);

/* 4. Таблица контактов */
CREATE TABLE CONTACTS (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERSON_ID       INTEGER NOT NULL,
    CONTACT_TYPE_ID INTEGER NOT NULL,
    CONTACT_VALUE   VARCHAR(255) NOT NULL,

    CONSTRAINT FK_CONTACTS_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES PERSONS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CONTACTS_TYPE FOREIGN KEY (CONTACT_TYPE_ID)
        REFERENCES CONTACT_TYPES (ID),
    CONSTRAINT CHK_CONTACTS_VAL CHECK (TRIM(CONTACT_VALUE) <> '')
);

/* Уникальный индекс от дубликатов контакта одного типа */
CREATE UNIQUE INDEX UQ_CONTACTS_TYPE_VAL ON CONTACTS COMPUTED BY (
    CAST(CONTACT_TYPE_ID AS VARCHAR(15)) || '|' || UPPER(TRIM(CONTACT_VALUE))
);

COMMIT;

