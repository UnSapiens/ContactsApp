CREATE OR ALTER PROCEDURE SP_SEARCH_PERSONS (
    P_GENDER       CHAR(1),
    P_FIO_PART     VARCHAR(100),
    P_CONTACT_PART VARCHAR(100),
    P_AGE          INTEGER
) RETURNS (
    ID          INTEGER,
    LAST_NAME   VARCHAR(100),
    FIRST_NAME  VARCHAR(100),
    MIDDLE_NAME VARCHAR(100),
    GENDER      CHAR(1),
    BIRTH_DATE  DATE,
    AGE         INTEGER
) AS
DECLARE VARIABLE V_FIO_FILTER     VARCHAR(102);
DECLARE VARIABLE V_CONTACT_FILTER VARCHAR(102);
DECLARE VARIABLE V_FULL_FIO       VARCHAR(305);
DECLARE VARIABLE V_CALC_AGE       INTEGER;
BEGIN
    IF (P_FIO_PART IS NOT NULL AND CHAR_LENGTH(TRIM(P_FIO_PART)) >= 2) THEN
        V_FIO_FILTER = '%' || UPPER(TRIM(P_FIO_PART)) || '%';
    ELSE
        V_FIO_FILTER = NULL;

    IF (P_CONTACT_PART IS NOT NULL AND CHAR_LENGTH(TRIM(P_CONTACT_PART)) >= 4) THEN
        V_CONTACT_FILTER = '%' || UPPER(TRIM(P_CONTACT_PART)) || '%';
    ELSE
        V_CONTACT_FILTER = NULL;

    FOR SELECT
            P.ID,
            P.LAST_NAME,
            P.FIRST_NAME,
            P.MIDDLE_NAME,
            P.GENDER,
            P.BIRTH_DATE
        FROM PERSONS P
        WHERE (:P_GENDER IS NULL OR TRIM(:P_GENDER) = '' OR P.GENDER = UPPER(TRIM(:P_GENDER)))
        ORDER BY P.LAST_NAME, P.FIRST_NAME, P.MIDDLE_NAME
        INTO :ID, :LAST_NAME, :FIRST_NAME, :MIDDLE_NAME, :GENDER, :BIRTH_DATE
    DO
    BEGIN
        V_CALC_AGE = DATEDIFF(YEAR, :BIRTH_DATE, CURRENT_DATE);
        IF (DATEADD(YEAR, :V_CALC_AGE, :BIRTH_DATE) > CURRENT_DATE) THEN
            V_CALC_AGE = :V_CALC_AGE - 1;
        AGE = :V_CALC_AGE;

        IF (:P_AGE IS NOT NULL AND :P_AGE >= 0 AND :AGE <> :P_AGE) THEN
            CONTINUE;

        IF (:V_FIO_FILTER IS NOT NULL) THEN
        BEGIN
            V_FULL_FIO = UPPER(TRIM(:LAST_NAME) || ' ' || TRIM(:FIRST_NAME) ||
                         COALESCE(' ' || TRIM(:MIDDLE_NAME), ''));
            IF (V_FULL_FIO NOT LIKE :V_FIO_FILTER) THEN
                CONTINUE;
        END

        IF (:V_CONTACT_FILTER IS NOT NULL) THEN
        BEGIN
            IF (NOT EXISTS (
                SELECT 1
                FROM CONTACTS C
                WHERE C.PERSON_ID = :ID
                  AND UPPER(C.CONTACT_VALUE) LIKE :V_CONTACT_FILTER
            )) THEN
                CONTINUE;
        END

        SUSPEND;
    END
END^

CREATE OR ALTER PROCEDURE SP_GET_PERSON_CONTACTS (
    P_PERSON_ID INTEGER
) RETURNS (
    ID           INTEGER,
    CONTACT_TYPE VARCHAR(50),
    CONTACT_VAL  VARCHAR(255)
) AS
BEGIN
    FOR SELECT
            C.ID,
            CT.NAME,
            C.CONTACT_VALUE
        FROM CONTACTS C
        JOIN CONTACT_TYPES CT ON CT.ID = C.CONTACT_TYPE_ID
        WHERE C.PERSON_ID = :P_PERSON_ID
        ORDER BY CT.ID, C.ID
        INTO :ID, :CONTACT_TYPE, :CONTACT_VAL
    DO
        SUSPEND;
END^

CREATE OR ALTER PROCEDURE SP_GET_CONTACT_TYPES
RETURNS (
    ID   INTEGER,
    CODE VARCHAR(20),
    NAME VARCHAR(50)
) AS
BEGIN
    FOR SELECT ID, CODE, NAME
        FROM CONTACT_TYPES
        ORDER BY ID
        INTO :ID, :CODE, :NAME
    DO
        SUSPEND;
END^

CREATE OR ALTER PROCEDURE SP_ADD_PERSON (
    P_LAST_NAME   VARCHAR(100),
    P_FIRST_NAME  VARCHAR(100),
    P_MIDDLE_NAME VARCHAR(100),
    P_GENDER      CHAR(1),
    P_BIRTH_DATE  DATE
) RETURNS (
    NEW_ID INTEGER
) AS
DECLARE VARIABLE V_LNAME VARCHAR(100);
DECLARE VARIABLE V_FNAME VARCHAR(100);
DECLARE VARIABLE V_MNAME VARCHAR(100);
BEGIN
    V_LNAME = TRIM(COALESCE(:P_LAST_NAME, ''));
    V_FNAME = TRIM(COALESCE(:P_FIRST_NAME, ''));
    V_MNAME = NULLIF(TRIM(COALESCE(:P_MIDDLE_NAME, '')), '');

    IF (V_LNAME = '' OR V_FNAME = '') THEN
        EXCEPTION EX_VALIDATION_ERR 'Фамилия и Имя обязательны для заполнения.';

    IF (:P_BIRTH_DATE IS NULL OR :P_BIRTH_DATE > CURRENT_DATE) THEN
        EXCEPTION EX_VALIDATION_ERR 'Дата рождения не может быть больше текущей.';

    INSERT INTO PERSONS (LAST_NAME, FIRST_NAME, MIDDLE_NAME, GENDER, BIRTH_DATE)
    VALUES (:V_LNAME, :V_FNAME, :V_MNAME, UPPER(TRIM(:P_GENDER)), :P_BIRTH_DATE)
    RETURNING ID INTO :NEW_ID;

    SUSPEND;
WHEN SQLCODE -803 DO
    EXCEPTION EX_DUPLICATE_DATA 'Человек с такими ФИО, полом и датой рождения уже существует.';
END^

CREATE OR ALTER PROCEDURE SP_ADD_CONTACT (
    P_PERSON_ID       INTEGER,
    P_CONTACT_TYPE_ID INTEGER,
    P_CONTACT_VALUE   VARCHAR(255)
) RETURNS (
    NEW_ID INTEGER
) AS
DECLARE VARIABLE V_CLEAN_VAL VARCHAR(255);
BEGIN
    V_CLEAN_VAL = TRIM(COALESCE(:P_CONTACT_VALUE, ''));

    IF (V_CLEAN_VAL = '') THEN
        EXCEPTION EX_VALIDATION_ERR 'Значение контакта не может быть пустым.';

    IF (NOT EXISTS (SELECT 1 FROM CONTACT_TYPES WHERE ID = :P_CONTACT_TYPE_ID)) THEN
        EXCEPTION EX_VALIDATION_ERR 'Указан несуществующий тип контакта.';

    INSERT INTO CONTACTS (PERSON_ID, CONTACT_TYPE_ID, CONTACT_VALUE)
    VALUES (:P_PERSON_ID, :P_CONTACT_TYPE_ID, :V_CLEAN_VAL)
    RETURNING ID INTO :NEW_ID;

    SUSPEND;
WHEN SQLCODE -803 DO
    EXCEPTION EX_DUPLICATE_DATA 'Такой контакт уже зарегистрирован в базе.';
END^

SET TERM ; ^

COMMIT;

