/* 3. Таблица контактов */
CREATE TABLE CONTACTS (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERSON_ID       INTEGER NOT NULL REFERENCES PERSONS(ID) ON DELETE CASCADE,
    CONTACT_TYPE_ID INTEGER NOT NULL REFERENCES CONTACT_TYPES(ID),
    CONTACT_VALUE   VARCHAR(255) NOT NULL
)^

/* Уникальный индекс по значению контакта (регистронезависимый) */
CREATE UNIQUE INDEX UX_CONTACTS_VALUE ON CONTACTS COMPUTED BY (
    UPPER(TRIM(CONTACT_VALUE))
)^

