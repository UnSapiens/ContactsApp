/* 1. Таблица людей */
CREATE TABLE PERSONS (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LAST_NAME   VARCHAR(100) NOT NULL,
    FIRST_NAME  VARCHAR(100) NOT NULL,
    MIDDLE_NAME VARCHAR(100),
    GENDER      CHAR(1) NOT NULL CHECK (GENDER IN ('M', 'F')), -- 'M' - Муж, 'F' - Жен
    BIRTH_DATE  DATE NOT NULL
)^

/* Уникальный индекс по ФИО + Дата рождения (регистронезависимый) */
CREATE UNIQUE INDEX UX_PERSONS_FIO_BDATE ON PERSONS COMPUTED BY (
    UPPER(TRIM(LAST_NAME)) || '|' || 
    UPPER(TRIM(FIRST_NAME)) || '|' || 
    UPPER(TRIM(COALESCE(MIDDLE_NAME, ''))) || '|' || 
    CAST(BIRTH_DATE AS VARCHAR(10))
)^

/* 2. Справочник типов контактов */
CREATE TABLE CONTACT_TYPES (
    ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL UNIQUE
)^

